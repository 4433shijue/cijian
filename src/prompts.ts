export function prompt(kind: PromptKind, prefs: Preferences, theater = false) {
  const override = prefs.prompts[kind];
  const guard = kind === "novel" && theater
    ? "本次同一回复包含正文与番外。以下扩写边界约束 text 正文和 facts；theaterHtml 可以按小剧场要求补充吐槽、心理与观众评论，不能混入 text 或 facts。\n" + guards.novel.replace(
      '只输出 JSON 对象 {"text":"正文","facts":[{"quote":"正文中一条事实的连续逐字摘录","knownBy":[]}]}',
      '只输出 JSON 对象，按 text、facts、theaterHtml 的顺序写字段，格式为 {"text":"正文","facts":[{"quote":"正文中一条事实的连续逐字摘录","knownBy":[]}],"theaterHtml":"小剧场的 HTML 与 CSS"}。先完整写完正文，再写简短的小剧场'
    ) : guards[kind];
  return (
    guard + "\n\n" + (override?.enabled ? override.text : defaults[kind])
  );
}
